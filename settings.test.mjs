import assert from "node:assert/strict";
import { DatabaseSync } from "node:sqlite";
import { mkdtempSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { createSettingsStore } from "./settings.js";

const directory = mkdtempSync(join(tmpdir(), "portfel-settings-"));
let db;
try {
  const path = join(directory, "portfolio.db");
  db = new DatabaseSync(path);
  db.exec(`CREATE TABLE transactions (id TEXT PRIMARY KEY, quantity REAL, price REAL, type TEXT, fee REAL);
    INSERT INTO transactions VALUES ('legacy', 2, 32.855, 'BUY', 0);`);
  let settings = createSettingsStore(db);
  assert.deepEqual(settings.get(), { costMethod: "FIFO", cashBalance: -65.71 });
  assert.deepEqual({ ...db.prepare("SELECT * FROM transactions").get() }, { id: "legacy", quantity: 2, price: 32.855, type: "BUY", fee: 0, cost_method: null });
  settings.save({ costMethod: "AVP", cashBalance: 0 });
  db.prepare("UPDATE transactions SET cost_method = 'FIFO' WHERE id = 'legacy'").run();
  assert.throws(() => settings.save({ costMethod: "OTHER" }), error => error.status === 400);
  assert.throws(() => settings.save(null), error => error.status === 400);
  assert.throws(() => db.exec("UPDATE transactions SET cost_method = 'OTHER'"));
  assert.deepEqual(settings.save({ cashBalance: 1234.56 }), { costMethod: "AVP", cashBalance: 1234.56 });
  assert.deepEqual(settings.save({ costMethod: "FIFO" }), { costMethod: "FIFO", cashBalance: 1234.56 });
  settings.save({ costMethod: "AVP" });
  for (const cashBalance of [-1, 1.001, null, "10", Infinity, NaN, 1e20]) {
    assert.throws(() => settings.save({ costMethod: "FIFO", cashBalance }), error => error.status === 400);
  }
  assert.deepEqual(settings.get(), { costMethod: "AVP", cashBalance: 1234.56 });
  db.close();
  db = new DatabaseSync(path);
  settings = createSettingsStore(db);
  assert.deepEqual(settings.get(), { costMethod: "AVP", cashBalance: 1234.56 });
  assert.equal(db.prepare("SELECT cost_method FROM transactions").get().cost_method, "FIFO");
  createSettingsStore(db);
  assert.equal(db.prepare("PRAGMA table_info(transactions)").all().filter(column => column.name === "cost_method").length, 1);
  settings.deposit({ amount: 100, date: "2026-10-27" });
  assert.equal(settings.get().cashBalance, 1334.56);
  db.prepare("UPDATE transactions SET quantity = 3 WHERE id = 'legacy'").run();
  assert.equal(settings.get().cashBalance, 1301.7);
  db.close();
  db = new DatabaseSync(path);
  settings = createSettingsStore(db);
  assert.equal(settings.get().cashBalance, 1301.7);
  assert.equal(settings.deposits()[0].amount, 100);
  settings.save({ costMethod: "FIFO" });
  assert.equal(settings.get().cashBalance, 1301.7);
  const withdrawal = settings.saveCash({ type: "WITHDRAWAL", date: "2026-10-27", amount: 100 });
  assert.equal(settings.get().cashBalance, 1201.7);
  db.close();
  db = new DatabaseSync(path);
  settings = createSettingsStore(db);
  assert.equal(settings.get().cashBalance, 1201.7);
  assert.equal(settings.cashOperations().length, 2);
  settings.removeCash("WITHDRAWAL", withdrawal.id);
  assert.equal(settings.get().cashBalance, 1301.7);
  db.exec("CREATE TABLE assets (id TEXT PRIMARY KEY, ticker TEXT, name TEXT, market TEXT); INSERT INTO assets VALUES ('issuer', 'PKO', 'PKO Bank Polski', 'XWAR')");
  const dividend = settings.saveCash({ type: "DIVIDEND", ticker: "PKO", date: "2026-10-27", amount: 81.25 });
  assert.equal(settings.get().cashBalance, 1382.95);
  assert.equal(settings.deposits().length, 1);
  db.close();
  db = new DatabaseSync(path);
  settings = createSettingsStore(db);
  assert.equal(settings.get().cashBalance, 1382.95);
  assert.equal(settings.cashOperations().find(item => item.type === "DIVIDEND").amount, 81.25);
  settings.removeCash("DIVIDEND", dividend.id);
  assert.equal(settings.get().cashBalance, 1301.7);
  const legacyId = Number(db.prepare("INSERT INTO cash_dividends (date, amount_cents, created_at) VALUES ('2026-10-27', 5000, 1)").run().lastInsertRowid);
  db.close();
  db = new DatabaseSync(path);
  settings = createSettingsStore(db);
  assert.equal(settings.get().cashBalance, 1351.7);
  assert.equal(settings.cashOperations().find(item => item.type === "DIVIDEND").ticker, null);
  settings.saveCash({ type: "DIVIDEND", date: "2026-10-27", amount: 50, ticker: "PKO" }, legacyId);
  assert.equal(settings.get().cashBalance, 1351.7);
  db.prepare("UPDATE assets SET ticker = 'NEW', name = 'Nowa nazwa' WHERE id = 'issuer'").run();
  assert.equal(settings.cashOperations().find(item => item.type === "DIVIDEND").ticker, "NEW");
  assert.equal(settings.cashOperations().find(item => item.type === "DIVIDEND").assetName, "Nowa nazwa");
  db.exec("PRAGMA foreign_keys = ON");
  assert.throws(() => db.prepare("DELETE FROM assets WHERE id = 'issuer'").run());
  console.log("Testy migracji i trwałości ustawień FIFO/AVP: OK");
} finally {
  db?.close();
  rmSync(directory, { recursive: true, force: true });
}
