import assert from "node:assert/strict";
import { DatabaseSync } from "node:sqlite";
import { mkdtempSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { createAssetStore } from "./assets.js";
import { calculatePortfolio } from "./portfolio.js";

const directory = mkdtempSync(join(tmpdir(), "portfel-assets-"));
let db;
try {
  const path = join(directory, "portfolio.db");
  db = new DatabaseSync(path);
  db.exec(`CREATE TABLE transactions (id TEXT PRIMARY KEY, created_at INTEGER, date TEXT, ticker TEXT, type TEXT, quantity REAL, price REAL, fee REAL);
    CREATE TABLE quotes (ticker TEXT PRIMARY KEY, price REAL);
    INSERT INTO transactions VALUES ('buy', 1, '2026-01-01', 'OLD', 'BUY', 10, 20, 5), ('sell', 2, '2026-02-01', 'OLD', 'SELL', 2, 30, 1);
    INSERT INTO quotes VALUES ('OLD', 25), ('QUOTEONLY', 10);`);
  const transactions = () => db.prepare("SELECT *, created_at AS createdAt FROM transactions").all();
  const quotes = () => Object.fromEntries(db.prepare("SELECT * FROM quotes").all().map(row => [row.ticker, row.price]));
  const before = calculatePortfolio(transactions(), quotes())[0];
  let store = createAssetStore(db);
  assert.deepEqual(store.list().map(asset => asset.ticker), ["OLD", "QUOTEONLY"]);
  const definition = { ticker: "NEW", name: 'Spółka <A> & "B"', symbols: [{ platform: "GPW", symbol: "NEW" }, { platform: "Inna platforma", symbol: "New Company" }] };
  store.save("OLD", definition);
  assert.equal(transactions().length, 2);
  assert.ok(transactions().every(row => row.ticker === "NEW"));
  assert.deepEqual(calculatePortfolio(transactions(), quotes())[0], { ...before, ticker: "NEW" });
  assert.equal(quotes().OLD, undefined);
  assert.equal(quotes().NEW, 25);
  store.ensure("NEW");
  createAssetStore(db); // Restart/migration must preserve edited names and mappings.
  assert.deepEqual(store.list().find(asset => asset.ticker === "NEW"), definition);
  assert.throws(() => store.save(null, definition), error => error.status === 409);
  assert.throws(() => store.save("MISSING", definition), error => error.status === 404);
  assert.throws(() => store.save(null, { ...definition, ticker: "OTHER" }), error => error.status === 409);
  assert.throws(() => store.save("NEW", { ...definition, symbols: [{ platform: "GPW", symbol: "A" }, { platform: "gpw", symbol: "B" }] }), error => error.status === 400);
  assert.throws(() => store.save("NEW", { ...definition, name: " " }), error => error.status === 400);
  assert.throws(() => store.save("NEW", { ...definition, symbols: [null] }), error => error.status === 400);
  assert.throws(() => store.save("NEW", { ...definition, ticker: "QUOTEONLY" }), error => error.status === 409);
  // Force a write failure after the asset update and verify complete rollback.
  db.exec("CREATE TRIGGER fail_rename BEFORE UPDATE ON transactions BEGIN SELECT RAISE(ABORT, 'test failure'); END;");
  assert.throws(() => store.save("NEW", { ...definition, ticker: "FAIL" }), /test failure/);
  assert.deepEqual(store.list().find(asset => asset.ticker === "NEW"), definition);
  assert.ok(transactions().every(row => row.ticker === "NEW"));
  db.exec("DROP TRIGGER fail_rename");
  store.save("NEW", { ...definition, symbols: [] });
  db.close();
  db = new DatabaseSync(path);
  store = createAssetStore(db);
  assert.deepEqual(store.list().find(asset => asset.ticker === "NEW"), { ...definition, symbols: [] });
  store.save("NEW", definition);
  const openTransactions = transactions();
  assert.throws(() => store.remove("NEW"), error => error.status === 409 && /otwartą pozycją/.test(error.message));
  assert.deepEqual(transactions(), openTransactions);
  assert.deepEqual(store.list().find(asset => asset.ticker === "NEW"), definition);
  assert.equal(db.prepare("SELECT COUNT(*) AS count FROM removed_assets").get().count, 0);
  db.exec("INSERT INTO transactions VALUES ('close', 3, '2026-03-01', 'NEW', 'SELL', 8, 30, 1)");
  const savedTransactions = transactions();
  const savedQuotes = quotes();
  const savedPositions = calculatePortfolio(savedTransactions, savedQuotes);
  db.exec("CREATE TRIGGER fail_remove BEFORE DELETE ON assets BEGIN SELECT RAISE(ABORT, 'delete failure'); END;");
  assert.throws(() => store.remove("NEW"), /delete failure/);
  assert.deepEqual(store.list().find(asset => asset.ticker === "NEW"), definition);
  assert.equal(db.prepare("SELECT COUNT(*) AS count FROM removed_assets").get().count, 0);
  db.exec("DROP TRIGGER fail_remove");
  store.remove("NEW");
  assert.ok(!store.list().some(asset => asset.ticker === "NEW"));
  assert.equal(db.prepare("SELECT COUNT(*) AS count FROM asset_symbols WHERE asset_ticker = 'NEW'").get().count, 0);
  assert.deepEqual(transactions(), savedTransactions);
  assert.deepEqual(quotes(), savedQuotes);
  assert.deepEqual(calculatePortfolio(transactions(), quotes()), savedPositions);
  assert.throws(() => store.remove("NEW"), error => error.status === 404);
  db.close();
  db = new DatabaseSync(path);
  store = createAssetStore(db);
  store.ensure("NEW");
  assert.ok(!store.list().some(asset => asset.ticker === "NEW"));
  store.save(null, definition);
  assert.deepEqual(store.list().find(asset => asset.ticker === "NEW"), definition);
  assert.equal(db.prepare("SELECT COUNT(*) AS count FROM removed_assets").get().count, 0);
  store.remove("QUOTEONLY");
  assert.equal(quotes().QUOTEONLY, 10);
  store.save(null, { ticker: "UNUSED", name: "Unused", symbols: [] });
  store.remove("UNUSED");
  assert.ok(!store.list().some(asset => asset.ticker === "UNUSED"));
  console.log("Testy aktywów: usuwanie, zachowanie portfela, ponowne dodanie, migracja, zapis, zmiana tickera, FIFO, walidacja, rollback i trwałość OK");
} finally {
  db?.close();
  rmSync(directory, { recursive: true, force: true });
}
